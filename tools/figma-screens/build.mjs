// Builds the Figma screens plugin (code.js) from three parts:
//   the screens kit, from the design system beside this repo (pastel-studio-theme/tools/figma-library/screens-kit.js),
//   Pastel Espresso's accent (solar-lime) from the design system's palette,
//   screens.js, Espresso's own components and screens.
// Run: node tools/figma-screens/build.mjs  (or npm run figma:screens), then run the plugin in Figma.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ACCENT = 'solar-lime';

// The design system: --ds=<its folder>, or the pastel-studio-theme beside the repo (a worktree
// is deeper, so look up the tree). --consts prints the app's colours and writes nothing: the
// design system's whole-file plugin (tools/figma-file) asks for them that way.
const dsArg = process.argv.find(a => a.startsWith('--ds='));
let dir = here, ds = dsArg ? dsArg.slice(5) : null;
while (!ds && dir !== dirname(dir)) { const c = join(dir, '..', 'pastel-studio-theme'); if (existsSync(join(c, 'tools', 'figma-library', 'screens-kit.js'))) { ds = c; break; } dir = dirname(dir); }
if (!ds) throw new Error('pastel-studio-theme not found beside this repo, or it has no tools/figma-library/screens-kit.js');

const kit = readFileSync(join(ds, 'tools', 'figma-library', 'screens-kit.js'), 'utf8');
const palette = JSON.parse(readFileSync(join(ds, 'packages', 'react', 'src', 'theme', 'palette.json'), 'utf8'));
// The order palette.json lists each preset's values in (packages/react/src/theme/presets.ts)
const TOKENS = ['accent', 'accent-hover', 'on-accent', 'on-accent-2', 'accent-container', 'on-accent-container', 'accent-text', 'focus-ring'];
if (!palette[ACCENT]) throw new Error(`No accent ${ACCENT} in the design system's palette`);
const accent = Object.fromEntries(TOKENS.map((t, i) => [t, String(palette[ACCENT].dark[i]).toUpperCase()]));
// Espresso's own colours (src/styles/foundation/tokens.css, dark theme): the drawer is tinted with
// the accent's hue, oklch(from var(--accent) L C h); the rest are plain values.
const lin = c => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = c => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function hueOf(hex) {
  const [R, G, B] = [1, 3, 5].map(i => lin(parseInt(hex.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B), m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B), s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, b = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  return Math.atan2(b, a);
}
function oklch(L, C, h) {
  const A = C * Math.cos(h), B = C * Math.sin(h);
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3, m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3, s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
  return '#' + rgb.map(x => Math.round(Math.min(1, Math.max(0, gam(x))) * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
}
const h = hueOf(accent.accent);
const colours = {
  'drawer-bg': oklch(0.145, 0.014, h), 'drawer-hover': oklch(0.243, 0.018, h), 'drawer-hover-2': oklch(0.284, 0.02, h), 'drawer-hover-3': oklch(0.324, 0.022, h),
  'surface-inset': '#121417', break: '#5EC8B8', 'break-hover': '#7AD6C8', 'on-break': '#00201C',
};
const screens = readFileSync(join(here, 'screens.js'), 'utf8');

const consts = [`const APP_ACCENT = ${JSON.stringify(accent)};`, `const APP_COLOURS = ${JSON.stringify(colours)};`];
if (process.argv.includes('--consts')) { console.log(consts.join('\n')); process.exit(0); }
const code = [
  '// Generated by tools/figma-screens/build.mjs: edit screens.js (or the kit in the design system), then build again.',
  ...consts,
  kit,
  screens,
].join('\n');
writeFileSync(join(here, 'code.js'), code);
console.log(`Built tools/figma-screens/code.js (accent ${ACCENT}, drawer ${colours['drawer-bg']}).`);
